function searchAreas(district, query) {
    const areas = AREAS_BY_DISTRICT[district] || [];
    if (!query) return areas;
    const q = query.trim().toLowerCase();
    const index = AREA_SEARCH_INDEX[district] || {};
    return areas.filter(area => {
        if (area.toLowerCase().includes(q)) return true;
        const variants = index[area] || [];
        return variants.some(v => v.includes(q));
    });
}
